    draw.text((W // 2, 1625), cta, fill=(255, 255, 255, 255), font=f_cta, anchor="mm")

    out_png.parent.mkdir(parents=True, exist_ok=True)
    canvas.convert("RGB").save(out_png, format="PNG")


