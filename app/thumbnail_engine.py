def _hex_to_rgb(hex_color: str) -> tuple[int, int, int]:
    c = (hex_color or "#FF2E93").strip().lstrip("#")
    if len(c) != 6:
        return (255, 46, 147)
    try:
        return (int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16))
    except ValueError:
        return (255, 46, 147)


def _strip_letterbox_bars(im: Image.Image) -> Image.Image:
    """
    Remove blurred or dark letterbox top/bottom bars generated by vertical 9:16 padding
    so thumbnail hero frames always use the sharp inner photo without dead space.
    """
    rgb = im.convert("RGB")
    w, h = rgb.size
    if w >= h or h < 360:
        return rgb
    arr = np.asarray(rgb, dtype=np.float32)
    # Row-wise horizontal gradient sharpness (edge energy along X) + brightness
    dx = np.abs(arr[:, 1:, :] - arr[:, :-1, :]).mean(axis=(1, 2))
    bright = arr.mean(axis=(1, 2))
    max_dx = float(np.percentile(dx, 92)) if len(dx) else 0.0
    if max_dx < 1.5:
        return rgb
    # Blurred padded zones have much lower high-frequency edge detail and/or lower brightness
    sharp_mask = (dx >= max_dx * 0.42) & (bright >= 14.0)
    idx = np.where(sharp_mask)[0]
    if len(idx) < 40:
        return rgb
    top = int(idx[0])
    bot = int(idx[-1]) + 1
    core_h = bot - top
    # Only strip if the core band clearly looks like a cropped widescreen inset inside 9:16
    if 0.28 * h <= core_h <= 0.86 * h:
        pad = max(0, min(6, int(core_h * 0.01)))
        return rgb.crop((0, max(0, top + pad), w, min(h, bot - pad)))
    return rgb


def _extract_video_frame_raw(video_path: Path, seek_sec: float, out_jpg: Path) -> bool:
    if not video_path.exists():
        return False
    ffmpeg = get_ffmpeg_exe()
    cmd = [
        ffmpeg,
        "-y",
        "-ss",
        f"{max(0.0, seek_sec):.2f}",
        "-i",
        str(video_path),
        "-frames:v",
        "1",
        "-vf",
        "scale=1280:-2:flags=lanczos",
        "-q:v",
        "2",
        str(out_jpg),
    ]
    res = subprocess.run(cmd, capture_output=True)
    if res.returncode == 0 and out_jpg.exists() and out_jpg.stat().st_size > 2048:
        return True
    if seek_sec > 0.2:
        cmd[3] = "0.10"
        res2 = subprocess.run(cmd, capture_output=True)
        return res2.returncode == 0 and out_jpg.exists() and out_jpg.stat().st_size > 2048
    return False


def _image_to_data_uri(im: Image.Image, max_side: int = 1280) -> str:
    rgb = im.convert("RGB")
    w, h = rgb.size
    if max(w, h) > max_side:
        scale = max_side / float(max(w, h))
        rgb = rgb.resize((max(64, int(w * scale)), max(64, int(h * scale))), Image.Resampling.LANCZOS)
    buf = io.BytesIO()
    rgb.save(buf, format="JPEG", quality=92, optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    return f"data:image/jpeg;base64,{b64}"


def _open_clean_image(path: Path) -> Image.Image | None:
    try:
        with Image.open(path) as im:
            cleaned = _strip_letterbox_bars(im)
            if cleaned.width < 120 or cleaned.height < 120:
                return None
            return cleaned
    except Exception:
        return None


def _collect_hero_images(project: MusicStoryProject, work_dir: Path) -> tuple[Image.Image | None, Image.Image | None]:
    """
    Collect up to two distinct, sharp, un-letterboxed photographs from the project:
    1) Primary hero image (honors `project.thumbnail_scene_index` if set, otherwise best sharp visual).
    2) Secondary detail/contrast image (from another scene or news asset).
    """
    tmp_dir = work_dir / "_thumb_tmp"
    tmp_dir.mkdir(parents=True, exist_ok=True)
    candidates: list[tuple[int, int, str, Image.Image]] = []
    seen_sigs: set[str] = set()

    def _add_pil(sc_idx: int, priority: int, tag: str, im: Image.Image | None) -> None:
        if im is None:
            return
        # Fingerprint tiny grayscale thumbnail so identical images across scenes aren't duplicated
        small = np.asarray(im.convert("L").resize((12, 12)), dtype=np.int16)
        sig = f"{int(small.mean())}_{int(small[:6].mean())}_{int(small[6:].mean())}"
        if sig in seen_sigs:
            return
        seen_sigs.add(sig)
        candidates.append((sc_idx, priority, tag, im))

    pref_idx = getattr(project, "thumbnail_scene_index", None)
    scenes = list(project.scenes or [])

    # Order scenes: preferred scene first, then scene 1..N
    ordered_scenes = sorted(
        scenes,
        key=lambda s: (0 if (pref_idx is not None and s.index == pref_idx) else s.index),
    )

    for sc in ordered_scenes:
        # 1. Raw overlay image (crisp uncropped 16:9 news photo)
        if sc.overlay_image_path and Path(sc.overlay_image_path).exists():
            im = _open_clean_image(Path(sc.overlay_image_path))
            _add_pil(sc.index, 100, "overlay", im)

        # 2. Scene video frame extracted raw (landscape sharp frame)
        if sc.video_path and Path(sc.video_path).exists():
            v_jpg = tmp_dir / f"vframe_s{sc.index:02d}.jpg"
            seek = float(getattr(sc, "video_start_sec", 0.0) or 0.0) + 1.2
            if _extract_video_frame_raw(Path(sc.video_path), seek, v_jpg):
                im = _open_clean_image(v_jpg)
                _add_pil(sc.index, 92, "video", im)

        # 3. Stripped scene_XX.png fallback
        if sc.image_path and Path(sc.image_path).exists():
            im = _open_clean_image(Path(sc.image_path))
            _add_pil(sc.index, 70, "scene_img", im)

    # Extra project-level centerpiece / downloaded news images
    if project.reel2_center_image and Path(project.reel2_center_image).exists():
        im = _open_clean_image(Path(project.reel2_center_image))
        _add_pil(0, 96 if pref_idx is None and project.niche != "gaming_news" else 65, "centerpiece", im)

    nm_dir = work_dir / "news_media"
    if nm_dir.exists():
        for img_p in sorted(nm_dir.glob("img_*.*"))[:6]:
            im = _open_clean_image(img_p)
            _add_pil(99, 85, "news_media", im)

    if not candidates:
        return None, None

    if pref_idx is not None:
        # Pick highest-priority candidate belonging to preferred scene first
        candidates.sort(key=lambda c: (c[0] == pref_idx, c[1]), reverse=True)
    else:
        candidates.sort(key=lambda c: (c[1], c[3].width), reverse=True)

    hero1 = candidates[0][3]
    hero2 = candidates[1][3] if len(candidates) > 1 else None
    return hero1, hero2


def _build_thumb_copy(project: MusicStoryProject) -> dict[str, Any]:
    is_gaming = getattr(project, "niche", "music_history") == "gaming_news" or project.style_preset == "vice_city_neon"
    game_or_artist = (project.artist or ("GTA 6" if is_gaming else "Música")).strip()

    custom_badge = (getattr(project, "thumbnail_badge", "") or "").strip()
    if custom_badge:
        badge = custom_badge[:36]
    elif is_gaming:
        conf = (project.fact_confidence or "").lower()
        title_low = f"{project.hook_title} {project.song_title}".lower()
        if "oficial" in conf or "rockstar" in title_low or "confirm" in title_low:
            badge = f"✅ OFICIAL • {game_or_artist.upper()}"
        elif any(k in title_low for k in ("vaz", "bomba", "ao vivo", "novo", "urgente", "data", "preço")):
            badge = f"🔥 BOMBA • {game_or_artist.upper()}"
        else:
            badge = f"🎮 RADAR {game_or_artist.upper()} • SHORTS"
    else:
        yr = f" • {project.year}" if project.year else ""
        badge = f"🎵 HISTÓRIA DA MÚSICA{yr}"

    custom_head = (getattr(project, "thumbnail_headline", "") or "").strip()
    if custom_head:
        raw_head = custom_head
    elif is_gaming:
        raw_head = (project.hook_title or project.song_title or game_or_artist).strip()
        raw_head = re.sub(r"#shorts\b", "", raw_head, flags=re.IGNORECASE).strip()
        raw_head = re.sub(r"\s*[-|•]\s*(?:ign|flow games|viciados|techtudo|msn|eurogamer|uol|terra).*$", "", raw_head, flags=re.I).strip()
    else:
        raw_head = (project.reel2_title or project.song_title or project.hook_title or "").strip()

    # Keep headline crisp & huge: target <= 42 chars (approx 5-8 words) so font size hits ~96-112px
    words = [w for w in raw_head.split() if w]
    if len(" ".join(words)) > 44:
        trimmed: list[str] = []
        cur_len = 0
        for w in words:
            if cur_len + len(w) + (1 if trimmed else 0) > 42 and len(trimmed) >= 4:
                break
            trimmed.append(w)
            cur_len += len(w) + 1
        words = trimmed
    clean_head = " ".join(words).strip(" .,:;-—") or game_or_artist
    if len(words) >= 5 and clean_head[-1] not in "!?.":
        clean_head += "!"

    # Build token list for smart highlight coloring
    hi_set = {w.strip(".,!?:;\"'()").upper() for w in _HIGHLIGHT_POWER_WORDS}
    if project.scenes and project.scenes[0].highlight_words:
        for hw in project.scenes[0].highlight_words:
            for part in str(hw).split():
                hi_set.add(part.strip(".,!?:;").upper())
    for part in game_or_artist.split():
        if len(part) >= 3:
            hi_set.add(part.upper())

    # Partition tokens cleanly into 2 balanced lines (or 3 if very long) without orphan short prepositions
    up_words = clean_head.upper().split()
    hi_flags: list[bool] = []
    for tok in up_words:
        clean_tok = re.sub(r"[^\wÀ-ÿ0-9]", "", tok)
        hi_flags.append(bool(clean_tok in hi_set or re.search(r"\d", clean_tok)))

    def _split_balanced(tokens: list[tuple[str, bool]]) -> list[list[tuple[str, bool]]]:
        n = len(tokens)
        total_len = len(" ".join(t[0] for t in tokens))
        if n <= 3 or total_len <= 16:
            return [tokens]
        # Candidate split counts: prefer 2 punchy wide lines whenever total <= 40 chars
        n_target = 2 if (total_len <= 40 and n <= 9) else 3
        if n_target == 2:
            best_idx = 1
            best_score = 1e9
            for i in range(1, n):
                l_txt = " ".join(t[0] for t in tokens[:i])
                r_txt = " ".join(t[0] for t in tokens[i:])
                if len(l_txt) > 22 or len(r_txt) > 22:
                    continue
                penalty = abs(len(l_txt) - len(r_txt))
                prev_w = tokens[i - 1][0].rstrip(":,-")
                next_w = tokens[i][0].rstrip(":,-")
                if prev_w in {"AO", "DE", "DA", "DO", "NO", "NA", "EM", "E", "COM", "POR", "SEM", "PRA"}:
                    penalty += 24
                if tokens[i - 1][0].endswith(":"):
                    penalty -= 10
                if next_w in {"VIVO", "JOGO", "REAL"} and prev_w in {"AO", "DE", "DO"}:
                    penalty += 24
                if penalty < best_score:
                    best_score = penalty
                    best_idx = i
            if best_score < 1e8:
                return [tokens[:best_idx], tokens[best_idx:]]

        # 3-line balanced split
        out_lines: list[list[tuple[str, bool]]] = []
        cur_line: list[tuple[str, bool]] = []
        cur_chars = 0
        for item in tokens:
            tok = item[0]
            prev_clean = cur_line[-1][0].rstrip(":,-") if cur_line else ""
            will_overflow = cur_chars + 1 + len(tok) > 18
            if cur_line and (
                cur_line[-1][0].endswith(":")
                or (will_overflow and prev_clean not in {"AO", "DE", "DA", "DO", "NO", "NA", "EM"})
                or len(cur_line) >= 4
            ):
                if len(out_lines) == 2:
                    cur_line.append(item)
                    cur_chars += 1 + len(tok)
                    continue
                out_lines.append(cur_line)
                cur_line = []
                cur_chars = 0
            cur_line.append(item)
            cur_chars += len(tok) + (1 if len(cur_line) > 1 else 0)
        if cur_line:
            out_lines.append(cur_line)
        return out_lines[:3]

    lines = _split_balanced(list(zip(up_words, hi_flags)))

    # Avoid highlighting EVERY word on a line; if >65% highlighted, keep only the strongest 2-3 words
    all_toks = [t for ln in lines for t in ln]
    if all_toks and sum(1 for _, h in all_toks if h) > max(2, int(len(all_toks) * 0.6)):
        kept = 0
        new_lines: list[list[tuple[str, bool]]] = []
        for ln in lines:
            nl = []
            for word, h in ln:
                cw = re.sub(r"[^\wÀ-ÿ0-9]", "", word)
                priority = bool(re.search(r"\d", cw) or cw in {"NOVO", "NOVA", "VÍDEO", "REAL", "OFICIAL", "SEGREDO", "VAZOU", "BOMBA", "GTA"})
                if h and priority and kept < 3:
                    nl.append((word, True))
                    kept += 1
                else:
                    nl.append((word, False))
            new_lines.append(nl)
        lines = new_lines

    if is_gaming:
        angle_txt = (project.topic_angle or "").strip()
        if not angle_txt or "resumo direto dos fatos" in angle_txt.lower():
            subline = f"O DETALHE QUE NINGUÉM VIU • {game_or_artist.upper()}"
        else:
            subline = angle_txt[:54].upper()
        cta_pill = "▶ ASSISTA AGORA • SHORTS 58S"
    else:
        subline = (project.reel2_subtitle or f"{project.artist} • {project.year}").strip(" •")[:54].upper()
        cta_pill = "▶ HISTÓRIA + MÚSICA"

    resolved_style = getattr(project, "thumbnail_style", "auto") or "auto"
    if resolved_style == "auto":
        if not is_gaming:
            resolved_style = "editorial_music"
        elif any(k in badge.lower() or k in clean_head.lower() for k in ("plantão", "urgente", "vazou", "bomba", "alerta")):
            resolved_style = "breaking_alert"
        else:
            resolved_style = "vice_city_magazine"

    return {
        "style": resolved_style,
        "badge": badge,
        "lines": lines,
        "plain_lines": [" ".join(w for w, _ in ln) for ln in lines],
        "subline": subline,
        "cta_pill": cta_pill,
        "is_gaming": is_gaming,
        "accent": project.accent_color or ("#FF2E93" if is_gaming else "#FF3B30"),
        "source_label": (project.genre or ("Games" if is_gaming else "Rock")).split("/")[0].strip().upper(),
    }


def _render_html_thumbnail_sync(html_doc: str, out_png: Path, browser_exe: str) -> None:
    async def _run() -> None:
        prof_dir = Path(tempfile.mkdtemp(prefix="mh_thumb_"))
        tmp_html = prof_dir / "thumb.html"
        tmp_html.write_text(html_doc, encoding="utf-8")

        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.bind(("127.0.0.1", 0))
            cdp_port = int(s.getsockname()[1])

        flags = 0
        if os.name == "nt":
            flags = subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.CREATE_NO_WINDOW

        proc = subprocess.Popen(
            [
                browser_exe,
                "--headless=new",
                "--disable-gpu-sandbox",
                "--no-first-run",
                "--no-default-browser-check",
                "--disable-background-networking",
                "--disable-crash-reporter",
                "--hide-scrollbars",
                "--mute-audio",
                f"--remote-debugging-port={cdp_port}",
                f"--user-data-dir={prof_dir}",
                f"--window-size={W},{H}",
                "about:blank",
            ],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            close_fds=True,
            creationflags=flags,
        )
        try:
            ws_url = None
            async with httpx.AsyncClient(timeout=1.5) as client:
                for _ in range(50):
                    try:
                        r = await client.get(f"http://127.0.0.1:{cdp_port}/json/list")
                        tabs = [t for t in r.json() if t.get("type") == "page"]
                        if tabs:
                            ws_url = tabs[0]["webSocketDebuggerUrl"]
                            break
                    except Exception:
                        await asyncio.sleep(0.06)
            if not ws_url:
                raise RuntimeError("CDP unavailable for thumbnail rendering.")

            async with websockets.connect(ws_url, max_size=32_000_000) as ws:
                mid = 0

                async def call(method: str, params: dict[str, Any] | None = None) -> dict[str, Any]:
                    nonlocal mid
                    mid += 1
                    rid = mid
                    await ws.send(json.dumps({"id": rid, "method": method, "params": params or {}}))
                    while True:
                        raw = await ws.recv()
                        msg = json.loads(raw)
                        if msg.get("id") == rid:
                            if "error" in msg:
                                raise RuntimeError(f"CDP {method}: {msg['error']}")
                            return msg.get("result", {})

                await call("Page.enable")
                await call(
                    "Emulation.setDeviceMetricsOverride",
                    {"width": W, "height": H, "deviceScaleFactor": 1, "mobile": False},
                )
                await call("Page.navigate", {"url": tmp_html.as_uri()})
                for _ in range(40):
                    st = await call(
                        "Runtime.evaluate",
                        {
                            "expression": "document.readyState === 'complete' && Array.from(document.images).every(i => i.complete)",
                            "returnByValue": True,
                        },
                    )
                    if st.get("result", {}).get("value") is True:
                        break
                    await asyncio.sleep(0.05)
                await asyncio.sleep(0.08)
                shot = await call(
                    "Page.captureScreenshot",
                    {"format": "png", "fromSurface": True, "captureBeyondViewport": False},
                )
                png_bytes = base64.b64decode(shot["data"])
                out_png.parent.mkdir(parents=True, exist_ok=True)
                out_png.write_bytes(png_bytes)
        finally:
            try:
                proc.terminate()
                proc.wait(timeout=2)
            except Exception:
                try:
                    proc.kill()
                except Exception as exc:
                    logger.debug("Falha ao forçar encerramento do processo de browser: %s", exc)
            shutil.rmtree(prof_dir, ignore_errors=True)

    asyncio.run(_run())


